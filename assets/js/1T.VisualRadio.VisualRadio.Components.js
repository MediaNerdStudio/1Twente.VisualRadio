function windOrigin(windDir){
  let windOrigin = '';
  if (windDir >= 348.75 || windDir < 11.25) windOrigin = 'N';
  else if (windDir >= 11.25 && windDir < 33.75) windOrigin = 'N-NO';
  else if (windDir >= 33.75 && windDir < 56.25) windOrigin = 'NO';
  else if (windDir >= 56.25 && windDir < 78.75) windOrigin = 'O-NO';
  else if (windDir >= 78.75 && windDir < 101.25) windOrigin = 'O';
  else if (windDir >= 101.25 && windDir < 123.75) windOrigin = 'O-ZO';
  else if (windDir >= 123.75 && windDir < 146.25) windOrigin = 'ZO';
  else if (windDir >= 146.25 && windDir < 168.75) windOrigin = 'Z-ZO';
  else if (windDir >= 168.75 && windDir < 191.25) windOrigin = 'Z';
  else if (windDir >= 191.25 && windDir < 213.75) windOrigin = 'Z-ZW';
  else if (windDir >= 213.75 && windDir < 236.25) windOrigin = 'ZW';
  else if (windDir >= 236.25 && windDir < 258.75) windOrigin = 'W-ZW';
  else if (windDir >= 258.75 && windDir < 281.25) windOrigin = 'W';
  else if (windDir >= 281.25 && windDir < 303.75) windOrigin = 'W-NW';
  else if (windDir >= 303.75 && windDir < 326.25) windOrigin = 'NW';
  else if (windDir >= 326.25 && windDir < 348.75) windOrigin = 'N-NW';
  return windOrigin;
}